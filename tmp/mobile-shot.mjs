/** 390px look at the coupon panel (Task 7, Step 6 asks for both widths). */
import { writeFileSync } from "node:fs";
const CDP = 9333, APP = "http://localhost:5174", TOKEN = process.env.STAFF_TOKEN;
const target = await (await fetch(`http://127.0.0.1:${CDP}/json/new?${encodeURIComponent(APP)}`, { method: "PUT" })).json();
const ws = new WebSocket(target.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) pending.get(m.id)(m); };
await new Promise((r) => (ws.onopen = r));
const send = (method, params = {}) => new Promise((res) => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method, params })); });
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const ev = async (e) => (await send("Runtime.evaluate", { expression: e, returnByValue: true })).result?.result?.value;
await send("Page.enable"); await send("Runtime.enable");
await send("Emulation.setDeviceMetricsOverride", { width: 390, height: 1600, deviceScaleFactor: 2, mobile: true });
await wait(2500);
await ev(`localStorage.setItem('access', ${JSON.stringify(TOKEN)}); localStorage.setItem('refresh', ${JSON.stringify(TOKEN)}); 1`);
await send("Page.navigate", { url: `${APP}/admin/coupons` }); await wait(6000);
console.log("WIDTH", await ev("innerWidth"), "OVERFLOW", await ev("document.documentElement.scrollWidth > innerWidth"));
console.log("HAS FORM", await ev("!!document.querySelector('form')"), "HAS LIST", await ev("document.body.innerText.includes('SALYCO10')"));
const r = await send("Page.captureScreenshot", { format: "png" });
writeFileSync("tmp/shots/admin-coupons-390.png", Buffer.from(r.result.data, "base64"));
ws.close(); await fetch(`http://127.0.0.1:${CDP}/json/close/${target.id}`); process.exit(0);
